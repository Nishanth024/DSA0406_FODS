import pandas as pd

data = {
    'Customer_ID': [101, 102, 101, 103, 102],
    'Order_Date': ['2026-01-05', '2026-01-10', '2026-01-15', '2026-01-20', '2026-01-25'],
    'Product_Name': ['Laptop', 'Mouse', 'Laptop', 'Keyboard', 'Mouse'],
    'Order_Quantity': [2, 3, 1, 4, 2]
}

order_data = pd.DataFrame(data)

order_data['Order_Date'] = pd.to_datetime(order_data['Order_Date'])

# 1. Total orders made by each customer
print("Total Orders by Each Customer:")
print(order_data.groupby('Customer_ID').size())

# 2. Average order quantity for each product
print("\nAverage Order Quantity by Product:")
print(order_data.groupby('Product_Name')['Order_Quantity'].mean())

# 3. Earliest and latest order dates
print("\nEarliest Order Date:")
print(order_data['Order_Date'].min())

print("\nLatest Order Date:")
print(order_data['Order_Date'].max())

import pandas as pd

data = {
    'Product': ['Laptop', 'Mouse', 'Keyboard', 'Laptop', 'Mouse', 'Monitor', 'Keyboard', 'Mouse'],
    'Quantity': [5, 20, 10, 8, 15, 6, 12, 25],
    'Order_Date': ['2026-10-02', '2026-10-05', '2026-10-08', '2026-10-10', '2026-10-12', '2026-10-15', '2026-10-18', '2026-10-20']
}

df = pd.DataFrame(data)
df['Order_Date'] = pd.to_datetime(df['Order_Date'])

# Filter sales for October 2026
start_date = '2026-10-01'
end_date = '2026-10-31'

monthly_data = df[
    (df['Order_Date'] >= start_date) &
    (df['Order_Date'] <= end_date)
]

# Find top 5 products by quantity sold
top_products = monthly_data.groupby('Product')['Quantity'].sum()
top_products = top_products.sort_values(ascending=False).head(5)

print("Top 5 Best-Selling Products:")
print(top_products)

